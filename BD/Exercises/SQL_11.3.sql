FROM ClassesWithAtLeast9Guns;

SELECT *
FROM BattlesWith3Ships;

DROP VIEW BritishShips;
DROP VIEW SunkShips;
DROP VIEW ClassesWithAtLeast9Guns;
DROP VIEW BattlesWith3Ships;